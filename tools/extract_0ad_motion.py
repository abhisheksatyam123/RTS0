#!/usr/bin/env python3
"""Generate RTS0's unit motion data from 0 A.D.'s simulation templates.

0 A.D. UnitMotion (CCmpUnitMotion.h PerformMove) moves a unit by its template's:
  * UnitMotion/Acceleration: metres per second squared. A unit gains speed at
    this rate up to its walk speed (instantly back down to it).
  * UnitMotion/InstantTurnAngle: radians. A unit facing further than this from
    its way on stops and turns; nearer, it moves on at cos(angle) of its speed.
  * Position/TurnRate: radians per second a stopped unit turns at.
  * Footprint/Circle@radius or Footprint/Square@width,depth: metres, the shape
    Formation.js GetAvgFootprint spaces formation members by.

Acceleration is written in RTS0 units, scaled like walk speeds
(extract_0ad_rosters.py SPEED_SCALE), so a unit takes 0.28's time to reach
its speed.

One row per civ roster template (same order as civ_roster_data.h) and one
per RTS0 UnitType for units without a roster template (extract_0ad_rosters.py's
GENERIC templates), as tools/extract_0ad_attack.py does.

Usage:
  python3 -I tools/extract_0ad_motion.py --0ad PATH/TO/0ad [--check]

Reads data/civs/rosters.json for the roster order and
binaries/data/mods/public/simulation from the 0 A.D. checkout. Writes
src/simulation/unit_motion_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import json
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "unit_motion_data.h")
ROSTERS = os.path.join(REPO, "data", "civs", "rosters.json")

_spec = importlib.util.spec_from_file_location("extract_0ad_rosters",
                                               os.path.join(REPO, "tools", "extract_0ad_rosters.py"))
ex = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ex)

UNIT_TYPES = ["UNIT_VILLAGER", "UNIT_SWORDSMAN", "UNIT_ARCHER", "UNIT_SPEARMAN", "UNIT_CAVALRY",
              "UNIT_TRADER", "UNIT_CATAPULT", "UNIT_HERO", "UNIT_TRIREME", "UNIT_ELEPHANT",
              "UNIT_SIEGE_RAM", "UNIT_HEALER", "UNIT_CHARIOT", "UNIT_WAR_DOG", "UNIT_BOLT_SHOOTER",
              "UNIT_FISHING_BOAT", "UNIT_MERCHANT_SHIP", "UNIT_FEMALE_CITIZEN", "UNIT_CARNYX",
              "UNIT_WORKER_ELEPHANT", "UNIT_ARCHER_MAIDEN", "UNIT_CAMEL", "UNIT_SCYTHED_CHARIOT",
              "UNIT_MINISTER", "UNIT_CATAFALQUE", "UNIT_TYPE_TECH", "UNIT_WAGON"]


def footprint(t):
    """Footprint width and depth in metres, as Footprint.js GetShape gives them to Formation.js."""
    sq = t.get("Footprint/Square")
    if sq is not None and "width" in sq.attrs:
        return float(sq.attrs["width"]), float(sq.attrs["depth"])
    c = t.get("Footprint/Circle")
    if c is not None and "radius" in c.attrs:
        return 2.0 * float(c.attrs["radius"]), 2.0 * float(c.attrs["radius"])
    return 1.0, 1.0


def row_of(t):
    return (t.num("UnitMotion/Acceleration", 35.0) * ex.SPEED_SCALE,
            t.num("UnitMotion/InstantTurnAngle", 1.5),
            t.num("Position/TurnRate", 14.0)) + footprint(t)


def collect(sim_root):
    loader = ex.TemplateLoader(sim_root)
    rosters = json.load(open(ROSTERS))
    units = []
    for u in rosters["units"]:
        name = "units/" + u["id"]
        if not loader.exists(name.split("|")[-1]):
            name = ex.GENERIC[u["class"]]  # RTS0-only rows (the male villager)
        units.append((u["id"], row_of(loader.load(name))))
    generic = []
    for cls in UNIT_TYPES:
        t = ex.generic_template(loader, cls)
        generic.append((cls, ex.GENERIC[cls] or "no template", row_of(t)))
    return units, generic


def f(x):
    s = repr(round(x, 4))
    return (s if "." in s or "e" in s else s + ".0") + "f"


def fields(row):
    a, ita, tr, fw, fd = row
    c = -2.0 if ita >= math.pi else math.cos(ita)
    return ", ".join((f(a), f(ita), f(tr), f(c), f(fw), f(fd)))


def emit(units, generic):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_motion.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h inside namespace rtso, after civ_roster_data.h.")
    w("#pragma once")
    w("")
    w("struct UnitMotionProfile {")
    w("\tfloat acceleration; // UnitMotion/Acceleration in RTS0 units/s^2 (0.28's m/s^2 x the speed scale)")
    w("\tfloat instant_turn_angle; // UnitMotion/InstantTurnAngle, radians")
    w("\tfloat turn_rate; // Position/TurnRate, radians per second")
    w("\tfloat cos_instant_turn; // cos(instant_turn_angle); -2 (no turn stops it) from pi up")
    w("\tfloat footprint_width, footprint_depth; // Footprint (circle: its diameter), metres")
    w("};")
    w("")
    w("inline constexpr uint16_t MOTION_TEMPLATE_COUNT = %d; // = CIV_UNIT_TEMPLATE_COUNT" % len(units))
    w("inline const UnitMotionProfile *motion_template_table() {")
    w("\tstatic const UnitMotionProfile kTable[MOTION_TEMPLATE_COUNT] = {")
    for uid, row in units:
        w("\t\t{%s}, // %s" % (fields(row), uid))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("// Units without a roster template, by UnitType (extract_0ad_rosters.py GENERIC).")
    w("inline constexpr uint8_t MOTION_CLASS_ROWS = %d; // = UNIT_TYPE_COUNT" % len(generic))
    w("inline const UnitMotionProfile *motion_class_table() {")
    w("\tstatic const UnitMotionProfile kTable[MOTION_CLASS_ROWS] = {")
    for cls, name, row in generic:
        w("\t\t{%s}, // %s: %s" % (fields(row), cls, name))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    units, generic = collect(sim_root)
    text = emit(units, generic)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("unit_motion_data.h is out of date")
        print("unit_motion_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print("wrote %s (%d templates, %d classes)" % (OUT_HEADER, len(units), len(generic)))


if __name__ == "__main__":
    main()
