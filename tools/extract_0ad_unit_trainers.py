#!/usr/bin/env python3
"""Generate src/simulation/unit_trainer_data.h: the roster units that train other units or research.

0 A.D. gives a few units a Trainer (components/Trainer.js): Athenian triremes train marines
and Cretan archers, Persian triremes train cavalry once Equine Transports is researched, and
Cyrus II trains Immortals. For each roster unit (civ_roster_data.h) this reads its template's
Trainer/Entities and Trainer/BatchTimeModifier. A trainee is a roster row; a trainee 0 A.D.
only has as a copy of a roster unit with an Identity/Requirements tech (the Persian
cavalry_*_b_trireme templates) becomes that roster unit with the tech as its requirement.
A roster unit's Researcher/Technologies (Athenian triremes: Iphicratean Reforms) become
UNIT_RESEARCH_ROWS.

Usage:
  python3 -I tools/extract_0ad_unit_trainers.py --0ad PATH/TO/0ad [--check]

The 0 A.D. data is CC BY-SA 3.0, (C) Wildfire Games; see docs/0AD_ATTRIBUTION.md.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_0ad_rosters import TemplateLoader, tech_enums  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "unit_trainer_data.h")
ROSTER = os.path.join(REPO, "src", "simulation", "civ_roster_data.h")

# Trainee templates that copy a roster unit and only add a requirement: suffix stripped.
COPY_SUFFIXES = ("_trireme",)


def roster_ids():
    with open(ROSTER, encoding="utf-8") as fh:
        return re.findall(r'^\t\t\{"([a-z0-9_/]+)", "(?:[^"\\]|\\.)*", "(?:[^"\\]|\\.)*", CIV_[A-Z]+, UNIT_', fh.read(), re.M)


def trainer_rows(loader, ids):
    have = set(ids)
    enums = tech_enums()
    rows, seen = [], set()
    for uid in ids:
        if uid in seen or not loader.exists("units/" + uid):
            continue
        seen.add(uid)
        node = loader.load("units/" + uid)
        if node.get("Trainer") is None:
            continue
        civ = node.value("Identity/Civ") or uid.split("/")[0]
        mod = float(node.value("Trainer/BatchTimeModifier") or 1.0)
        for ent in node.tokens("Trainer/Entities"):
            ent = ent.replace("{civ}", civ)
            if not ent.startswith("units/"):
                continue
            tid = ent[len("units/"):]
            tech = "TECH_NONE"
            if tid not in have:
                base = next((tid[:-len(s)] for s in COPY_SUFFIXES if tid.endswith(s)), None)
                if base is None or base not in have:
                    raise SystemExit(f"{uid} trains {tid}, which is not a roster row")
                reqs = loader.load(ent).tokens("Identity/Requirements/Techs")
                techs = [enums[t] for t in reqs if t in enums]
                if len(techs) != 1:
                    raise SystemExit(f"{tid}: expected one known requirement tech, got {reqs}")
                tid, tech = base, techs[0]
            rows.append((uid, tid, tech, mod))
    return rows


def researcher_rows(loader, ids):
    enums = tech_enums()
    rows, seen = [], set()
    for uid in ids:
        if uid in seen or not loader.exists("units/" + uid):
            continue
        seen.add(uid)
        node = loader.load("units/" + uid)
        if node.get("Researcher") is None:
            continue
        civ = node.value("Identity/Civ") or uid.split("/")[0]
        for tech in node.tokens("Researcher/Technologies"):
            tech = tech.replace("{civ}", civ)
            if tech not in enums:
                raise SystemExit(f"{uid} researches {tech}, which RTS0's tech table lacks")
            rows.append((uid, enums[tech]))
    return rows


def emit(rows, research):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_unit_trainers.py from 0 A.D.'s unit templates")
    w("// (Trainer/Entities, Trainer/BatchTimeModifier, Researcher/Technologies). Do not edit by hand.")
    w("// 0 A.D. data is CC BY-SA 3.0, see docs/0AD_ATTRIBUTION.md.")
    w("#ifndef RTSO_UNIT_TRAINER_DATA_H")
    w("#define RTSO_UNIT_TRAINER_DATA_H")
    w("")
    w("#include <cstdint>")
    w("")
    w('#include "tech_data.h"')
    w("")
    w("namespace rtso {")
    w("")
    w("// A roster unit (`trainer`) that trains the roster unit `trainee` (0 A.D. Trainer on a")
    w("// unit), once its owner has `tech` (TECH_NONE: no requirement beyond the trainee's own).")
    w("struct UnitTrainerRow {")
    w("\tconst char *trainer;")
    w("\tconst char *trainee;")
    w("\tuint8_t tech;")
    w("\tfloat batch_time_modifier;")
    w("};")
    w("")
    w("inline constexpr UnitTrainerRow UNIT_TRAINER_ROWS[] = {")
    for uid, tid, tech, mod in rows:
        w(f'\t{{"{uid}", "{tid}", {tech}, {mod!r}f}},')
    w("};")
    w("")
    w("// A roster unit that researches `tech` (0 A.D. Researcher on a unit).")
    w("struct UnitResearchRow {")
    w("\tconst char *researcher;")
    w("\tuint8_t tech;")
    w("};")
    w("")
    w("inline constexpr UnitResearchRow UNIT_RESEARCH_ROWS[] = {")
    for uid, tech in research:
        w(f'\t{{"{uid}", {tech}}},')
    w("};")
    w("")
    w("} // namespace rtso")
    w("")
    w("#endif // RTSO_UNIT_TRAINER_DATA_H")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zeroad", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sim_root = os.path.join(a.zeroad, "binaries", "data", "mods", "public", "simulation")
    loader = TemplateLoader(sim_root)
    ids = roster_ids()
    text = emit(trainer_rows(loader, ids), researcher_rows(loader, ids))
    if a.check:
        with open(OUT_HEADER, encoding="utf-8") as fh:
            if fh.read() != text:
                print(f"{OUT_HEADER} is out of date; rerun tools/extract_0ad_unit_trainers.py")
                return 1
        print("unit_trainer_data.h is up to date")
        return 0
    with open(OUT_HEADER, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {OUT_HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
