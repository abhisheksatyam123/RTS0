#!/usr/bin/env python3
"""Generate RTS0's per-civ starting units from 0 A.D.'s civ StartEntities.

0 A.D.'s random maps place each player's StartEntities (simulation/data/civs/<civ>.json)
with rmgen-common player.js placeStartingEntities: the civic centre at the base, then
each further entry j as a row of Count units 6 tiles out at angle
BUILDING_ORIENTATION - PI * (1 - j / 2). The civic centre is the map's to place, so
only the unit entries are written, each with its index j in the civ's list.

Usage:
  python3 -I tools/extract_0ad_start_entities.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/start_entities_data.h. --check fails if the checked-in file differs.
"""

import argparse
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "start_entities_data.h")

# Civ ids as in extract_0ad_rosters.py (14 is CIV_GAIA, so the Germans are 15).
CIVS = ["athen", "spart", "pers", "rome", "cart", "mace", "brit", "gaul",
        "iber", "maur", "kush", "ptol", "sele", "han", "germ"]
CIV_ENUM = ["CIV_ATHENIANS", "CIV_SPARTANS", "CIV_PERSIANS", "CIV_ROMANS",
            "CIV_CARTHAGINIANS", "CIV_MACEDONIANS", "CIV_BRITONS", "CIV_GAULS",
            "CIV_IBERIANS", "CIV_MAURYANS", "CIV_KUSHITES", "CIV_PTOLEMIES",
            "CIV_SELEUCIDS", "CIV_HAN", "CIV_GERMANS"]


def rows(zad):
    civ_dir = os.path.join(zad, "binaries", "data", "mods", "public", "simulation", "data", "civs")
    out = []
    for civ, enum in zip(CIVS, CIV_ENUM):
        with open(os.path.join(civ_dir, civ + ".json"), encoding="utf-8") as f:
            ents = json.load(f).get("StartEntities", [])
        for j, e in enumerate(ents):
            t = e["Template"].replace("{civ}", civ)
            if not t.startswith("units/"):
                continue
            out.append((enum, t[len("units/"):], int(e.get("Count", 1)), j))
    return out


def emit(rs):
    w = []
    w.append("// GENERATED by tools/extract_0ad_start_entities.py from 0 A.D. 0.28")
    w.append("// simulation/data/civs/*.json StartEntities (CC BY-SA 3.0, Wildfire Games). Do not edit by hand.")
    w.append("#ifndef RTSO_START_ENTITIES_DATA_H")
    w.append("#define RTSO_START_ENTITIES_DATA_H")
    w.append("")
    w.append("#include <cstdint>")
    w.append("")
    w.append("namespace rtso {")
    w.append("")
    w.append("// One StartEntities unit entry: Count of the roster template, as entry `index` of the")
    w.append("// civ's list (the civic centre is entry 0).")
    w.append("struct StartEntity {")
    w.append("\tuint8_t civ;")
    w.append("\tconst char *tmpl; // roster id (template path under units/)")
    w.append("\tuint8_t count;")
    w.append("\tuint8_t index;")
    w.append("};")
    w.append("")
    w.append("inline constexpr int START_ENTITY_COUNT = %d;" % len(rs))
    w.append("inline const StartEntity *start_entity_table() {")
    w.append("\tstatic const StartEntity kTable[START_ENTITY_COUNT] = {")
    for enum, t, n, j in rs:
        w.append('\t\t{%s, "%s", %d, %d},' % (enum, t, n, j))
    w.append("\t};")
    w.append("\treturn kTable;")
    w.append("}")
    w.append("")
    w.append("} // namespace rtso")
    w.append("")
    w.append("#endif // RTSO_START_ENTITIES_DATA_H")
    return "\n".join(w) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--0ad", dest="zad", required=True, help="0 A.D. source checkout")
    ap.add_argument("--check", action="store_true", help="fail if the output is stale")
    args = ap.parse_args()
    text = emit(rows(args.zad))
    if args.check:
        with open(OUT_HEADER, encoding="utf-8") as f:
            if f.read() != text:
                print("start_entities_data.h is stale: re-run tools/extract_0ad_start_entities.py", file=sys.stderr)
                return 1
        return 0
    with open(OUT_HEADER, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT_HEADER, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
