#!/usr/bin/env python3
"""Generate RTS0's attack target preferences from 0 A.D.'s simulation templates.

0 A.D. units pick what to attack by Attack/<type>/PreferredClasses: an ordered
token list, each token a class or a "+"-joined set of classes ("!" negates),
as MatchesClassList reads them. Attack.js GetPreference gives a target the
index of the first token it matches (the lowest over the entity's attack
types), and UnitAI AttackEntitiesByPreference attacks the closest target of
the best preference, then entities that match none.

Writes, for each civ roster template (civ_roster_data.h order) and each RTS0
UnitType without one, the preference terms of its attacks and its own
classes as a target; and the classes of each RTS0 BuildingType (structures
are targets too). Only the classes some PreferredClasses names are kept.

Usage:
  python3 -I tools/extract_0ad_preferences.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/preference_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "preference_data.h")
ROSTERS = os.path.join(REPO, "data", "civs", "rosters.json")
MAX_TERMS = 4


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(REPO, "tools", name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ex = _load("extract_0ad_rosters")
atk = _load("extract_0ad_attack")

ATTACK_TYPES = ("Melee", "Ranged", "Capture", "Slaughter")


def preferences_of(t):
    """[(preference index, [classes required], [classes forbidden])] over the entity's attack types."""
    terms = []
    for kind in ATTACK_TYPES:
        a = t.get("Attack/" + kind)
        if a is None:
            continue
        for i, tok in enumerate(a.tokens("PreferredClasses")):
            req = [c for c in tok.split("+") if not c.startswith("!")]
            forbid = [c[1:] for c in tok.split("+") if c.startswith("!")]
            term = (i, tuple(sorted(req)), tuple(sorted(forbid)))
            if term not in terms:
                terms.append(term)
    terms.sort()
    if len(terms) > MAX_TERMS:
        sys.exit("more than %d PreferredClasses terms" % MAX_TERMS)
    return terms


def collect(sim_root):
    loader = ex.TemplateLoader(sim_root)
    rosters = json.load(open(ROSTERS))
    units = []
    for u in rosters["units"]:
        name = "units/" + u["id"]
        if not loader.exists(name.split("|")[-1]):
            name = ex.GENERIC[u["class"]]  # RTS0-only rows (the male villager)
        t = loader.load(name)
        units.append((u["id"], preferences_of(t), ex.classes_of(t)))
    generic = []
    for cls in atk.UNIT_TYPES:
        t = ex.generic_template(loader, cls)
        generic.append((cls, ex.GENERIC[cls] or "no template", preferences_of(t), ex.classes_of(t)))
    buildings = []
    for bld, name in atk.BUILDINGS + atk.civ_buildings():
        buildings.append((bld, name, ex.classes_of(loader.load(name))))
    buildings.append(("default", "template_structure", ex.classes_of(loader.load("template_structure"))))
    return units, generic, buildings


def emit(units, generic, buildings):
    names = set()
    for _, terms, _ in units:
        for _, req, forbid in terms:
            names.update(req)
            names.update(forbid)
    for _, _, terms, _ in generic:
        for _, req, forbid in terms:
            names.update(req)
            names.update(forbid)
    names = sorted(names)
    if len(names) > 8:
        sys.exit("more than 8 preference classes: widen PrefClasses")
    bit = {n: 1 << i for i, n in enumerate(names)}

    def bits(classes):
        return sum(bit[c] for c in classes if c in bit)

    def prefs(terms):
        cells = ["{%d, 0x%02x, 0x%02x}" % (i, bits(req), bits(forbid)) for i, req, forbid in terms]
        while len(cells) < MAX_TERMS:
            cells.append("{0, 0, 0}")
        return "{%d, {%s}}" % (len(terms), ", ".join(cells))

    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_preferences.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// 0 A.D. Attack/<type>/PreferredClasses (Attack.js GetPreference, UnitAI AttackEntitiesByPreference).")
    w("// Included by sim_types.h inside namespace rtso, after civ_attack_data.h.")
    w("#pragma once")
    w("")
    w("// The classes some PreferredClasses names, one bit each.")
    w("enum PrefClass : uint8_t {")
    for n in names:
        w("\tPC_%s = 0x%02x," % (n.upper(), bit[n]))
    w("};")
    w("")
    w("// One PreferredClasses token: a target with all of `all` and none of `none` matches.")
    w("struct PrefTerm { uint8_t index; uint8_t all, none; };")
    w("struct PrefProfile { uint8_t count; PrefTerm term[%d]; }; // terms by index, over the attack types" % MAX_TERMS)
    w("// A unit's PreferredClasses and its own preference classes as a target.")
    w("struct PrefUnitRow { PrefProfile prefs; uint8_t classes; };")
    w("")
    w("inline constexpr uint16_t PREF_TEMPLATE_COUNT = %d; // = CIV_UNIT_TEMPLATE_COUNT" % len(units))
    w("inline const PrefUnitRow *pref_template_table() {")
    w("\tstatic const PrefUnitRow kTable[PREF_TEMPLATE_COUNT] = {")
    for uid, terms, classes in units:
        w("\t\t{%s, 0x%02x}, // %s" % (prefs(terms), bits(classes), uid))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("inline constexpr uint8_t PREF_CLASS_ROWS = %d; // = UNIT_TYPE_COUNT" % len(generic))
    w("// Units without a roster template, by UnitType (extract_0ad_rosters.py GENERIC).")
    w("inline const PrefUnitRow *pref_class_table() {")
    w("\tstatic const PrefUnitRow kTable[PREF_CLASS_ROWS] = {")
    for cls, name, terms, classes in generic:
        w("\t\t{%s, 0x%02x}, // %s: %s" % (prefs(terms), bits(classes), cls, name))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("inline constexpr uint8_t PREF_BUILDING_ROWS = %d; // BuildingTypes; one more row for any other structure" % (len(buildings) - 1))
    w("// Each BuildingType's preference classes as a target.")
    w("inline const uint8_t *pref_building_classes() {")
    w("\tstatic const uint8_t kTable[PREF_BUILDING_ROWS + 1] = {")
    for bld, name, classes in buildings:
        w("\t\t0x%02x, // %s: %s" % (bits(classes), bld, name))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    units, generic, buildings = collect(sim_root)
    text = emit(units, generic, buildings)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("preference_data.h is out of date")
        print("preference_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    n = sum(1 for _, terms, _ in units if terms)
    print("wrote %s (%d of %d templates prefer targets)" % (OUT_HEADER, n, len(units)))


if __name__ == "__main__":
    main()
