#!/usr/bin/env python3
"""Generate RTS0's territory influence data from 0 A.D.'s simulation templates.

0 A.D. structures claim territory through components/TerritoryInfluence.js, read by
CCmpTerritoryManager::CalculateTerritories:
  * TerritoryInfluence/Radius (metres) and Weight: the structure's tile starts at
    Weight and each tile outwards loses Weight x tile size / Radius (times the
    tile's cost, x362/256 on a diagonal), so the claim fades out at Radius.
  * TerritoryInfluence/Root: civic centres, wonders and a few civ structures;
    only territory flood-connected to one of its owner's roots is connected.
A template without TerritoryInfluence (walls, docks, fields, outposts, ...)
claims none.

One row per RTS0 BuildingType, mapped to templates as tools/extract_0ad_attack.py
does. Radii are RTS0 map units (x0.25, 1 unit = 4 m as the maps are ported), so a territory covers the same share of the map as in 0.28.

Usage:
  python3 -I tools/extract_0ad_territory.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/territory_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "territory_data.h")
SCALE = 0.25  # map space: 1 RTS0 unit = 4 m (tools/port_0ad_maps.py), as territory is drawn on the map

_spec = importlib.util.spec_from_file_location("extract_0ad_attack",
                                               os.path.join(REPO, "tools", "extract_0ad_attack.py"))
atk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(atk)
ex = atk.ex


def row_of(t):
    if t.value("TerritoryInfluence/Radius") in (None, ""):
        return None
    radius = t.num("TerritoryInfluence/Radius")
    weight = int(t.num("TerritoryInfluence/Weight"))
    if radius <= 0 or weight <= 0:
        return None
    return {"radius": radius * SCALE, "radius_m": radius, "weight": weight,
            "root": t.value("TerritoryInfluence/Root") == "true"}


def f(v):
    s = ("%.4f" % v).rstrip("0")
    return (s + "0" if s.endswith(".") else s) + "f"


def emit(rows):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_territory.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h inside namespace rtso.")
    w("#pragma once")
    w("")
    w("// 0 A.D. TerritoryInfluence. radius is RTS0 map units (x0.25: 1 unit = 4 m), 0 = claims no territory.")
    w("struct TerritoryInfluenceInfo {")
    w("\tfloat radius; // Radius")
    w("\tuint16_t weight; // Weight")
    w("\tbool root; // Root: connects the territory around it")
    w("};")
    w("")
    w("inline constexpr uint8_t TERRITORY_INFLUENCE_ROWS = %d;" % len(rows))
    w("inline const TerritoryInfluenceInfo &territory_influence_info(uint8_t type) {")
    w("\tstatic const TerritoryInfluenceInfo kTable[TERRITORY_INFLUENCE_ROWS + 1] = {")
    for bld, name, r in rows:
        if r is None:
            w("\t\t{0.0f, 0, false}, // %s: %s" % (bld, name))
        else:
            w("\t\t{%s, %d, %s}, // %s: %s (%g m)" % (f(round(r["radius"], 4)), r["weight"],
                                                    "true" if r["root"] else "false", bld, name, r["radius_m"]))
    w("\t\t{0.0f, 0, false}, // out of range")
    w("\t};")
    w("\treturn kTable[type < TERRITORY_INFLUENCE_ROWS ? type : TERRITORY_INFLUENCE_ROWS];")
    w("}")
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    loader = ex.TemplateLoader(sim_root)
    rows = [(bld, name, row_of(loader.load(name))) for bld, name in atk.BUILDINGS + atk.civ_buildings()]
    text = emit(rows)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("territory_data.h is out of date")
        print("territory_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print("wrote %s (%d building types, %d claim territory, %d roots)" % (
        OUT_HEADER, len(rows), sum(1 for r in rows if r[2]), sum(1 for r in rows if r[2] and r[2]["root"])))


if __name__ == "__main__":
    main()
