#!/usr/bin/env python3
"""Generate RTS0's splash damage data from 0 A.D.'s simulation templates.

0 A.D. gives some attacks an area effect, Attack/<type>/Splash:
  * Shape: Circular (quadratic falloff from the impact point) or Linear (a
    strip Range long and Range/5 wide, along the missile's direction).
  * Range: the area's size in metres.
  * FriendlyFire: whether it also hurts the attacker's own and allied units.
  * Damage/{Hack,Pierce,Crush}: the damage at the centre, before resistance.
Attack.js GetSplashData reads it and helpers/Attack.js CauseDamageOverArea
applies it where the attack lands (DelayedDamage.js Hit), for melee attacks
too. Stone throwers, bolt shooters, siege warships, melee elephants and the
longsword mixin's swordsmen have one.

One splash index per civ roster template (same order as civ_roster_data.h)
and one per RTS0 UnitType for units without a roster template, each for the
unit's primary attack (ranged if it has one, else melee), as
extract_0ad_attack.py does. Index 0 means no splash; the distinct splash rows
follow.

Usage:
  python3 -I tools/extract_0ad_splash.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/splash_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "splash_data.h")
ROSTERS = os.path.join(REPO, "data", "civs", "rosters.json")


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(REPO, "tools", name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ex = _load("extract_0ad_rosters")
atk = _load("extract_0ad_attack")

SHAPES = {"Circular": 1, "Linear": 2}


def splash_of(t):
    """(shape, range m, friendly fire, hack, pierce, crush) of the primary attack's Splash, or None."""
    a, _ranged = ex.primary_attack(t)
    s = a.get("Splash") if a is not None else None
    if s is None:
        return None
    shape = s.value("Shape", "")
    if shape not in SHAPES:
        sys.exit("unknown Splash shape %r" % shape)
    return (SHAPES[shape], s.num("Range"), s.value("FriendlyFire", "false") == "true",
            s.num("Damage/Hack"), s.num("Damage/Pierce"), s.num("Damage/Crush"))


def collect(sim_root):
    loader = ex.TemplateLoader(sim_root)
    rosters = json.load(open(ROSTERS))
    units = []
    for u in rosters["units"]:
        name = "units/" + u["id"]
        if not loader.exists(name.split("|")[-1]):
            name = ex.GENERIC[u["class"]]  # RTS0-only rows (the male villager)
        units.append((u["id"], splash_of(loader.load(name))))
    generic = [(cls, ex.GENERIC[cls], splash_of(loader.load(ex.GENERIC[cls]))) for cls in atk.UNIT_TYPES]
    return units, generic


def f(x):
    return repr(float(x)) + "f"


def emit(units, generic):
    rows = [None]
    for s in [s for _, s in units] + [s for _, _, s in generic]:
        if s is not None and s not in rows:
            rows.append(s)
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_splash.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// 0 A.D. Attack/<type>/Splash (Attack.js GetSplashData, helpers/Attack.js CauseDamageOverArea).")
    w("// Included by sim_types.h inside namespace rtso, after civ_attack_data.h.")
    w("#pragma once")
    w("")
    w("enum SplashShape : uint8_t { SPLASH_NONE = 0, SPLASH_CIRCULAR = 1, SPLASH_LINEAR = 2 };")
    w("")
    w("struct SplashProfile {")
    w("\tuint8_t shape;      // SplashShape")
    w("\tfloat range;        // 0 A.D. metres")
    w("\tbool friendly_fire; // also hurts the attacker's own and allied entities")
    w("\tfloat hack, pierce, crush; // damage at the centre, before resistance")
    w("};")
    w("")
    w("inline constexpr uint8_t SPLASH_PROFILE_COUNT = %d; // row 0 = no splash" % len(rows))
    w("inline const SplashProfile *splash_profiles() {")
    w("\tstatic const SplashProfile kTable[SPLASH_PROFILE_COUNT] = {")
    w("\t\t{SPLASH_NONE, 0.0f, false, 0.0f, 0.0f, 0.0f},")
    for r in rows[1:]:
        w("\t\t{%s, %s, %s, %s, %s, %s}," % ("SPLASH_CIRCULAR" if r[0] == 1 else "SPLASH_LINEAR", f(r[1]),
                                           "true" if r[2] else "false", f(r[3]), f(r[4]), f(r[5])))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("inline constexpr uint16_t SPLASH_TEMPLATE_COUNT = %d; // = CIV_UNIT_TEMPLATE_COUNT" % len(units))
    w("// Splash row of each civ roster template's primary attack.")
    w("inline const uint8_t *splash_template_index() {")
    w("\tstatic const uint8_t kTable[SPLASH_TEMPLATE_COUNT] = {")
    for uid, s in units:
        if s is not None:
            w("\t\t%d, // %s" % (rows.index(s), uid))
        else:
            w("\t\t0,")
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("inline constexpr uint8_t SPLASH_CLASS_ROWS = %d; // = UNIT_TYPE_COUNT" % len(generic))
    w("// Units without a roster template, by UnitType (extract_0ad_rosters.py GENERIC).")
    w("inline const uint8_t *splash_class_index() {")
    w("\tstatic const uint8_t kTable[SPLASH_CLASS_ROWS] = {")
    for cls, name, s in generic:
        w("\t\t%d, // %s: %s" % (rows.index(s) if s is not None else 0, cls, name))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    units, generic = collect(sim_root)
    text = emit(units, generic)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("splash_data.h is out of date")
        print("splash_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    n = sum(1 for _, s in units if s is not None)
    print("wrote %s (%d of %d templates splash, %d rows)" % (OUT_HEADER, n, len(units), text.count("\t\t{") - 1))


if __name__ == "__main__":
    main()
