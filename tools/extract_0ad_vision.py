#!/usr/bin/env python3
"""Generate RTS0's structure vision ranges from 0 A.D.'s simulation templates.

0 A.D. structures see through components/Vision.js (CCmpVision): Vision/Range in
metres, inherited down the template tree (template_structure 4 m, Civic Centre
90 m, house 20 m, fields 0, ...). A foundation sees nothing
(special/filter/foundation.xml), which the simulation handles itself.

One row per RTS0 BuildingType, mapped to templates as tools/extract_0ad_attack.py
does. Ranges are RTS0 units (x COMBAT_DISTANCE_SCALE 0.28, as attack ranges and
unit vision).

Usage:
  python3 -I tools/extract_0ad_vision.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/vision_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "vision_data.h")
SCALE = 0.28  # COMBAT_DISTANCE_SCALE (civ_attack_data.h)

_spec = importlib.util.spec_from_file_location("extract_0ad_attack",
                                               os.path.join(REPO, "tools", "extract_0ad_attack.py"))
atk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(atk)
ex = atk.ex


def row_of(t):
    v = t.value("Vision/Range")
    return float(v) if v not in (None, "") else 0.0


def f(v):
    s = ("%.4f" % v).rstrip("0")
    return (s + "0" if s.endswith(".") else s) + "f"


def emit(rows):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_vision.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h inside namespace rtso.")
    w("#pragma once")
    w("")
    w("// 0 A.D. Vision/Range of each finished structure, RTS0 units (COMBAT_DISTANCE_SCALE); 0 = sees nothing.")
    w("inline constexpr uint8_t STRUCTURE_VISION_ROWS = %d;" % len(rows))
    w("inline float structure_vision_range(uint8_t type) {")
    w("\tstatic const float kTable[STRUCTURE_VISION_ROWS + 1] = {")
    for bld, name, metres in rows:
        w("\t\t%s, // %s: %s (%g m)" % (f(round(metres * SCALE, 4)), bld, name, metres))
    w("\t\t0.0f, // out of range")
    w("\t};")
    w("\treturn kTable[type < STRUCTURE_VISION_ROWS ? type : STRUCTURE_VISION_ROWS];")
    w("}")
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    loader = ex.TemplateLoader(sim_root)
    rows = [(bld, name, row_of(loader.load(name))) for bld, name in atk.BUILDINGS + atk.civ_buildings()]
    text = emit(rows)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("vision_data.h is out of date")
        print("vision_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print("wrote %s (%d building types)" % (OUT_HEADER, len(rows)))


if __name__ == "__main__":
    main()
