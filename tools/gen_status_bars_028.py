#!/usr/bin/env python3
"""Write src/presentation/status_bars_data.h: each animal's 0 A.D. 0.28
StatusBars (BarWidth, BarHeight, HeightOffset, in metres), resolved through
the template's parents, for the animals in src/simulation/gaia_data.h.

    python3 tools/gen_status_bars_028.py /path/to/0ad-0.28/simulation/templates
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def status_bars(templates: Path, name: str) -> dict:
	chain = []
	while name:
		p = templates / (name + ".xml")
		if not p.exists():
			break
		s = p.read_text()
		chain.append(s)
		m = re.search(r'<Entity parent="([^"]+)"', s)
		name = m.group(1).split("|")[-1] if m else None
	out = {}
	for s in reversed(chain):
		m = re.search(r"<StatusBars[^>]*>(.*?)</StatusBars>", s, re.S)
		if m:
			for k, v in re.findall(r"<(\w+)>([\d.]+)</\1>", m.group(1)):
				out[k] = float(v)
	return out


def main() -> None:
	templates = Path(sys.argv[1])
	gaia = (ROOT / "src/simulation/gaia_data.h").read_text()
	names = re.findall(r'\{"(fauna_\w+)"', gaia)
	rows = []
	for n in names:
		sb = status_bars(templates, "gaia/" + n)
		rows.append('\t\t{"%s", %.3ff, %.3ff, %.1ff},' % (n, sb.get("BarWidth", 2.0), sb.get("BarHeight", 0.333), sb.get("HeightOffset", 5.0)))
	out = ROOT / "src/presentation/status_bars_data.h"
	out.write_text("""// Generated by tools/gen_status_bars_028.py from 0 A.D. 0.28 simulation/templates/gaia.
// Do not edit by hand.
#pragma once

#include <cstring>

namespace rtso {

// 0 A.D. StatusBars of an animal template, in metres.
struct StatusBarsSize {
	const char *template_name;
	float bar_width, bar_height, height_offset;
};

inline StatusBarsSize fauna_status_bars(const char *template_name) {
	static const StatusBarsSize kTable[] = {
%s
	};
	for (const auto &r : kTable)
		if (std::strcmp(r.template_name, template_name) == 0) return r;
	return {template_name, 2.0f, 0.333f, 5.0f};
}

} // namespace rtso
""" % "\n".join(rows))
	print("wrote", out, len(rows), "animals")


if __name__ == "__main__":
	main()
