#!/usr/bin/env python3
"""Generate src/simulation/research_order_data.h: each technology's place in its
researcher's 0 A.D. 0.28 Researcher/Technologies list.

Petra's gameState.findAvailableTech (common-api gamestate.js:768) walks its own
entities in creation order and each one's Researcher list in template order, so
Simulation::petra_available_techs sorts a structure's techs by this rank. A pair_*
entry ranks both of its technologies at the pair's place. Ranks come from the
generic template of the tech's researcher (tools/extract_0ad_techs.py BUILDINGS),
then from the civs' own structures; a tech found in neither ranks 255.

Usage:
    python3 tools/extract_0ad_research_order.py --public PATH [--out src/simulation/research_order_data.h]

PATH is 0 A.D.'s public.zip or a directory it was unzipped into.
The 0 A.D. data is CC BY-SA 3.0, (C) Wildfire Games; see docs/0AD_ATTRIBUTION.md.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_0ad_techs as techs  # noqa: E402


def tech_names(header: str) -> list[str]:
    """The template_name column of tech_data.h's rows, in TechnologyId order."""
    rows = re.findall(r'^\t\t\{".*, "([^"]*)"\},$', open(header).read(), re.M)
    if not rows:
        sys.exit(f"no technology rows in {header}")
    return rows


def ranks(src: techs.Source, civ: str | None, template: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for i, t in enumerate(techs.template_researchables(src, template)):
        for c in ([civ] if civ else techs.CIVS + ["generic"]):
            for name in techs.pair_members(src, t.replace("{civ}", c)):
                out.setdefault(name, i)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--public", required=True)
    ap.add_argument("--tech-data", default="src/simulation/tech_data.h")
    ap.add_argument("--out", default="src/simulation/research_order_data.h")
    args = ap.parse_args()
    src = techs.Source(args.public)

    rank: dict[str, int] = {}
    for _, tpl in techs.BUILDINGS:
        for name, i in ranks(src, None, tpl).items():
            rank.setdefault(name, i)
    for civ in techs.CIVS:
        d = os.path.join(src.root, f"simulation/templates/structures/{civ}") if not src.zip else None
        names = (sorted(f[:-4] for f in os.listdir(d) if f.endswith(".xml")) if d and os.path.isdir(d) else
                 sorted(n.rsplit("/", 1)[1][:-4] for n in (src.zip.namelist() if src.zip else [])
                        if n.startswith(f"simulation/templates/structures/{civ}/") and n.endswith(".xml")))
        for stem in names:
            for name, i in ranks(src, civ, f"structures/{civ}/{stem}").items():
                rank.setdefault(name, i)

    names = tech_names(args.tech_data)
    vals = [min(rank.get(n, 255), 255) if n else 255 for n in names]
    with open(args.out, "w") as f:
        f.write("// Generated by tools/extract_0ad_research_order.py from 0 A.D. 0.28 (CC BY-SA 3.0,\n")
        f.write("// (C) Wildfire Games). Do not edit by hand.\n")
        f.write("// A technology's place in its researcher's Researcher/Technologies list.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write(f"inline constexpr uint16_t TECH_RESEARCH_RANK_ROWS = {len(vals)};\n")
        f.write("inline constexpr uint8_t kTechResearchRank[TECH_RESEARCH_RANK_ROWS] = {\n")
        for i in range(0, len(vals), 16):
            f.write("\t" + ", ".join(str(v) for v in vals[i:i + 16]) + ",\n")
        f.write("};\n")
    missing = [n for n, v in zip(names, vals) if n and v == 255]
    print(f"{len(vals)} technologies, {len(missing)} with no rank: {' '.join(missing[:20])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
