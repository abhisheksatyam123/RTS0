#!/usr/bin/env python3
"""Generate RTS0's technology requirement tooltips and specific names from 0 A.D. 0.28's
technologies.

selection_panels.js shows a technology's requirementsTooltip ("Unlocked in Town Phase.",
"Requires five Village Structures.") on its research button while its requirements fail,
and names it with getEntityNamesFormatted: the civ's specificName ("Kōmopolis") with the
genericName. One row per TechnologyId of src/simulation/tech_data.h (its "// <json name>"
comments); a *_generic phase also takes the civ's own phase_*_<civ>.json name.

Usage:
  python3 -I tools/extract_0ad_tech_tooltips.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/tech_tooltip_data.h. --check fails if the checked-in file differs.
"""

import argparse
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "simulation", "tech_tooltip_data.h")
ENUM_ROW = re.compile(r"^\tTECH_(\w+) = (\d+), // (\S+)")
CIV_ROW = re.compile(r"\{CIV_(\w+), \"(\w+)\", ")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    tech_dir = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation", "data", "technologies")
    civs = {}
    with open(os.path.join(REPO, "src", "simulation", "sim_types.h"), encoding="utf-8") as f:
        for line in f:
            m = CIV_ROW.search(line)
            if m:
                civs.setdefault(m.group(2), m.group(1))
    names = {}
    rows = []
    with open(os.path.join(REPO, "src", "simulation", "tech_data.h"), encoding="utf-8") as f:
        for line in f:
            m = ENUM_ROW.match(line.rstrip("\n"))
            if not m:
                continue
            path = os.path.join(tech_dir, m.group(3) + ".json")
            tip = ""
            specific = {}
            if os.path.exists(path):
                with open(path, encoding="utf-8") as j:
                    data = json.load(j)
                tip = data.get("requirementsTooltip", "")
                specific = dict(data.get("specificName") or {})
            if m.group(3).endswith("_generic"):
                for code in civs:
                    own = os.path.join(tech_dir, m.group(3)[: -len("generic")] + code + ".json")
                    if os.path.exists(own):
                        with open(own, encoding="utf-8") as j:
                            specific.update(json.load(j).get("specificName") or {})
            names[m.group(1)] = {civs[c]: n for c, n in specific.items() if c in civs}
            rows.append((int(m.group(2)), m.group(1), m.group(3), tip))
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_tech_tooltips.py from 0 A.D. 0.28's")
    w("// simulation/data/technologies/*.json requirementsTooltip and specificName; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h after tech_data.h, inside namespace rtso.")
    w("#pragma once")
    w("")
    w("// The research button's text while a technology's requirements fail (nullptr: none).")
    w("inline const char *tech_requirements_tooltip(uint8_t tech) {")
    w("\tswitch (tech) {")
    for _, name, json_name, tip in sorted(rows):
        if tip:
            w(f"\t\tcase TECH_{name}: return {c_str(tip)}; // {json_name}")
    w("\t\tdefault: return nullptr;")
    w("\t}")
    w("}")
    w("")
    w("// The technology's specificName for `civ` (nullptr: the generic name alone).")
    w("inline const char *tech_specific_name(uint8_t tech, uint8_t civ) {")
    w("\tswitch (tech) {")
    for _, name, json_name, _tip in sorted(rows):
        if not names[name]:
            continue
        w(f"\t\tcase TECH_{name}: // {json_name}")
        w("\t\t\tswitch (civ) {")
        for civ, n in sorted(names[name].items()):
            w(f"\t\t\t\tcase CIV_{civ}: return {c_str(n)};")
        w("\t\t\t\tdefault: return nullptr;")
        w("\t\t\t}")
    w("\t\tdefault: return nullptr;")
    w("\t}")
    w("}")
    text = "\n".join(out) + "\n"
    if args.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("tech_tooltip_data.h is out of date", file=sys.stderr)
                return 1
        print("tech_tooltip_data.h is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT} ({sum(1 for r in rows if r[3])} of {len(rows)} technologies have one)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
