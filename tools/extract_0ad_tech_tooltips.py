#!/usr/bin/env python3
"""Generate RTS0's technology requirement tooltips from 0 A.D. 0.28's technologies.

selection_panels.js shows a technology's requirementsTooltip ("Unlocked in Town Phase.",
"Requires five Village Structures.") on its research button while its requirements fail.
One string per TechnologyId of src/simulation/tech_data.h (its "// <json name>" comments).

Usage:
  python3 -I tools/extract_0ad_tech_tooltips.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/tech_tooltip_data.h. --check fails if the checked-in file differs.
"""

import argparse
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "simulation", "tech_tooltip_data.h")
ENUM_ROW = re.compile(r"^\tTECH_(\w+) = (\d+), // (\S+)")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    tech_dir = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation", "data", "technologies")
    rows = []
    with open(os.path.join(REPO, "src", "simulation", "tech_data.h"), encoding="utf-8") as f:
        for line in f:
            m = ENUM_ROW.match(line.rstrip("\n"))
            if not m:
                continue
            path = os.path.join(tech_dir, m.group(3) + ".json")
            tip = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8") as j:
                    tip = json.load(j).get("requirementsTooltip", "")
            rows.append((int(m.group(2)), m.group(1), m.group(3), tip))
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_tech_tooltips.py from 0 A.D. 0.28's")
    w("// simulation/data/technologies/*.json requirementsTooltip; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h after tech_data.h, inside namespace rtso.")
    w("#pragma once")
    w("")
    w("// The research button's text while a technology's requirements fail (nullptr: none).")
    w("inline const char *tech_requirements_tooltip(uint8_t tech) {")
    w("\tswitch (tech) {")
    for _, name, json_name, tip in sorted(rows):
        if tip:
            w(f"\t\tcase TECH_{name}: return {c_str(tip)}; // {json_name}")
    w("\t\tdefault: return nullptr;")
    w("\t}")
    w("}")
    text = "\n".join(out) + "\n"
    if args.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("tech_tooltip_data.h is out of date", file=sys.stderr)
                return 1
        print("tech_tooltip_data.h is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT} ({sum(1 for r in rows if r[3])} of {len(rows)} technologies have one)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
