#!/usr/bin/env python3
"""Generate RTS0's selection overlays from 0 A.D.'s simulation templates.

0 A.D. CCmpSelectable draws a selected or hovered unit's overlay as one
textured quad on the ground (UpdateDynamicOverlay):
  * Selectable/Overlay/Texture/MainTexture and MainTextureMask: the shape
    (art/textures/selection/<size>/<name>.png): an ellipse for most units, an
    arrow for champions, a star for heroes, a plus for healers, a rounded
    rectangle for siege and a cartouche for warships and the catafalque.
  * Selectable/Overlay/Shape/Circle@radius or Square@width,depth, else the
    Footprint: the quad's size in metres, turned with the unit (a circle of
    radius r is a 2r square).
  * Selectable/Overlay/AlwaysVisible: heroes show their overlay unselected,
    desaturated, at 0.65 alpha.

One row per civ roster template (same order as civ_roster_data.h), one per
RTS0 UnitType for units without a roster template (extract_0ad_rosters.py's
GENERIC templates), as tools/extract_0ad_motion.py does, and one per animal of
src/simulation/gaia_data.h.

Usage:
  python3 -I tools/extract_0ad_selectable.py --0ad PATH/TO/0ad [--check]

Writes src/presentation/selection_overlay_data.h. --check fails if the
checked-in file differs.
"""

import argparse
import importlib.util
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "presentation", "selection_overlay_data.h")
ROSTERS = os.path.join(REPO, "data", "civs", "rosters.json")
GAIA = os.path.join(REPO, "src", "simulation", "gaia_data.h")

_spec = importlib.util.spec_from_file_location("extract_0ad_motion",
                                               os.path.join(REPO, "tools", "extract_0ad_motion.py"))
mo = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mo)
ex = mo.ex


def texture(t):
    """The overlay's texture, e.g. 128x128/ellipse (its mask is <name>_mask)."""
    v = t.value("Selectable/Overlay/Texture/MainTexture", "128x128/ellipse.png")
    return v[:-4] if v.endswith(".png") else v


def size(t):
    """The quad's width and depth in metres (CCmpSelectable halfSizeX and halfSizeZ, doubled)."""
    sq = t.get("Selectable/Overlay/Shape/Square")
    if sq is not None and "width" in sq.attrs:
        return float(sq.attrs["width"]), float(sq.attrs["depth"])
    c = t.get("Selectable/Overlay/Shape/Circle")
    if c is not None and "radius" in c.attrs:
        return 2.0 * float(c.attrs["radius"]), 2.0 * float(c.attrs["radius"])
    return mo.footprint(t)


def row_of(t):
    w, d = size(t)
    return texture(t), w, d, t.get("Selectable/Overlay/AlwaysVisible") is not None


def collect(sim_root):
    loader = ex.TemplateLoader(sim_root)
    rosters = json.load(open(ROSTERS))
    units = []
    for u in rosters["units"]:
        name = "units/" + u["id"]
        if not loader.exists(name.split("|")[-1]):
            name = ex.GENERIC[u["class"]]
        units.append((u["id"], row_of(loader.load(name))))
    generic = [(cls, ex.GENERIC[cls] or "no template", row_of(ex.generic_template(loader, cls)))
               for cls in mo.UNIT_TYPES]
    fauna = [(n, row_of(loader.load("gaia/" + n)))
             for n in re.findall(r'\{"(fauna_\w+)"', open(GAIA).read())]
    return units, generic, fauna


def fields(row):
    tex, w, d, always = row
    return '"%s", %s, %s, %s' % (tex, mo.f(w), mo.f(d), "true" if always else "false")


def emit(units, generic, fauna):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_selectable.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("#include <cstring>")
    w("")
    w("namespace rtso {")
    w("")
    w("// CCmpSelectable's overlay: assets/textures/selection/<texture>.png and <texture>_mask.png on a")
    w("// width x depth metre quad turned with the unit (depth along its facing).")
    w("struct SelectionOverlay {")
    w("\tconst char *texture;")
    w("\tfloat width, depth;")
    w("\tbool always_visible; // Overlay/AlwaysVisible: shown unselected, desaturated, at 0.65 alpha")
    w("};")
    w("")
    w("inline constexpr uint16_t SELECTION_TEMPLATE_ROWS = %d; // = CIV_UNIT_TEMPLATE_COUNT" % len(units))
    w("inline const SelectionOverlay *selection_template_table() {")
    w("\tstatic const SelectionOverlay kTable[SELECTION_TEMPLATE_ROWS] = {")
    for uid, row in units:
        w("\t\t{%s}, // %s" % (fields(row), uid))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("// Units without a roster template, by UnitType (extract_0ad_rosters.py GENERIC).")
    w("inline constexpr uint8_t SELECTION_CLASS_ROWS = %d; // = UNIT_TYPE_COUNT" % len(generic))
    w("inline const SelectionOverlay *selection_class_table() {")
    w("\tstatic const SelectionOverlay kTable[SELECTION_CLASS_ROWS] = {")
    for cls, name, row in generic:
        w("\t\t{%s}, // %s: %s" % (fields(row), cls, name))
    w("\t};")
    w("\treturn kTable;")
    w("}")
    w("")
    w("// An animal's overlay by its gaia/<template_name>.")
    w("inline SelectionOverlay fauna_selection_overlay(const char *template_name) {")
    w("\tstruct Row {")
    w("\t\tconst char *name;")
    w("\t\tSelectionOverlay o;")
    w("\t};")
    w("\tstatic const Row kTable[] = {")
    for n, row in fauna:
        w('\t\t{"%s", {%s}},' % (n, fields(row)))
    w("\t};")
    w("\tfor (const Row &r : kTable)")
    w("\t\tif (std::strcmp(r.name, template_name) == 0) return r.o;")
    w('\treturn {"128x256/ellipse", 2.0f, 4.0f, false}; // template_unit_fauna')
    w("}")
    w("")
    w("} // namespace rtso")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    text = emit(*collect(sim_root))
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("selection_overlay_data.h is out of date")
        print("selection_overlay_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print("wrote %s" % OUT_HEADER)


if __name__ == "__main__":
    main()
