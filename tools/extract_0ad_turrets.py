#!/usr/bin/env python3
"""Generate RTS0's turret points from 0 A.D.'s TurretHolder templates.

Reads, under binaries/data/mods/public/simulation/templates:
  * structures/<civ>/wall_long.xml, wall_gate.xml and outpost.xml (TurretHolder/TurretPoints)
  * units/<civ>/*.xml for every roster unit, to check that Turretable units are exactly
    the ranged infantry (template_unit_infantry_ranged and the ranged infantry champions
    and heroes), the rule simulation.cpp applies

An RTS0 wall segment and gate are one 2x2 cell, much shorter than 0 A.D.'s walls, so each
keeps the civ's points that fit on it: wall_long's points for a segment, wall_gate's for a
gate. Offsets are scaled by COMBAT_DISTANCE_SCALE (0.28), as attack ranges and footprints are.

Usage:
  python3 -I tools/extract_0ad_turrets.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/turret_data.h. --check regenerates into memory and fails if the
checked-in file differs.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_0ad_rosters import CIVS, CIV_ENUM, TemplateLoader  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "turret_data.h")
ROSTER = os.path.join(REPO, "src", "simulation", "civ_roster_data.h")

SCALE = 0.28  # COMBAT_DISTANCE_SCALE in civ_attack_data.h
HALF_CELL = 1.0  # half of a one-cell structure (Simulation::GRID 2)
MAX_POINTS = 16

# RTS0 structure -> the civ template whose turret points it uses.
KINDS = [("BLD_WALL_SEGMENT", "wall_long"), ("BLD_GATE", "wall_gate"), ("BLD_OUTPOST", "outpost")]


def points(loader, civ, stem):
    name = f"structures/{civ}/{stem}"
    if not loader.exists(name):
        return []
    tp = loader.load(name).get("TurretHolder/TurretPoints")
    if tp is None:
        return []
    out = []
    for p in tp.children.values():
        x, y, z = (float(p.value(k)) * SCALE for k in ("X", "Y", "Z"))
        if p.value("AllowedClasses") or p.value("Template"):
            raise SystemExit(f"{name}: AllowedClasses / Template turret points are not ported")
        if abs(x) <= HALF_CELL and abs(z) <= HALF_CELL:
            out.append((round(x, 3), round(y, 3), round(z, 3)))
    return sorted(out, key=lambda q: (q[2], q[0]))


def check_turretable(loader):
    with open(ROSTER, encoding="utf-8") as fh:
        ids = re.findall(r'^\t\t\{"([a-z_]+/[a-z0-9_]+)"', fh.read(), re.M)
    for uid in ids:
        name = "units/" + uid
        if not loader.exists(name):
            continue
        t = loader.load(name)
        classes = set((t.value("Identity/Classes") or "").split()) | set((t.value("Identity/VisibleClasses") or "").split())
        rule = "Infantry" in classes and "Ranged" in classes
        if (t.get("Turretable") is not None) != rule:
            raise SystemExit(f"{uid}: Turretable does not match the ranged-infantry rule")


def f(x):
    return repr(float(x)) + "f"


def emit(table):
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_turrets.py from 0 A.D.'s TurretHolder templates")
    w("// (structures/<civ>/wall_long.xml, wall_gate.xml, outpost.xml). Do not edit by hand:")
    w("// change the tool and regenerate. 0 A.D. data is CC BY-SA 3.0, see docs/0AD_ATTRIBUTION.md.")
    w("#ifndef RTSO_TURRET_DATA_H")
    w("#define RTSO_TURRET_DATA_H")
    w("")
    w("#include <cstdint>")
    w("")
    w("namespace rtso {")
    w("")
    w("// A TurretPoint offset from the holder's centre in RTS0 units (x, z on the ground, y up).")
    w("struct TurretPoint {")
    w("\tfloat x, y, z;")
    w("};")
    w("")
    w(f"inline constexpr int TURRET_POINTS_MAX = {MAX_POINTS};")
    w("")
    w("struct TurretPointSet {")
    w("\tuint8_t count;")
    w("\tTurretPoint pt[TURRET_POINTS_MAX];")
    w("};")
    w("")
    w("// [civ][0 wall segment, 1 gate, 2 outpost]")
    w(f"inline constexpr TurretPointSet TURRET_POINTS[{len(CIVS)}][{len(KINDS)}] = {{")
    for civ, enum in zip(CIVS, CIV_ENUM):
        w(f"\t{{ // {enum}")
        for (bld, stem) in KINDS:
            pts = table[(civ, stem)][:MAX_POINTS]
            body = ", ".join(f"{{{f(x)}, {f(y)}, {f(z)}}}" for x, y, z in pts)
            w(f"\t\t{{{len(pts)}, {{{body}}}}}, // {bld}: {civ}/{stem}")
        w("\t},")
    w("};")
    w("")
    w("} // namespace rtso")
    w("")
    w("#endif // RTSO_TURRET_DATA_H")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zeroad", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sim_root = os.path.join(a.zeroad, "binaries", "data", "mods", "public", "simulation")
    loader = TemplateLoader(sim_root)
    check_turretable(loader)
    table = {(civ, stem): points(loader, civ, stem) for civ in CIVS for _, stem in KINDS}
    text = emit(table)
    if a.check:
        with open(OUT_HEADER) as fh:
            if fh.read() != text:
                print(f"{OUT_HEADER} is out of date; rerun tools/extract_0ad_turrets.py")
                return 1
        print("turret_data.h is up to date")
        return 0
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT_HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
