#!/usr/bin/env python3
"""Generate RTS0's batch training data from 0 A.D.'s simulation templates.

0 A.D. trains a batch of n units in BuildTime * n^BatchTimeModifier
(components/Trainer.js GetBatchTime), where Trainer/BatchTimeModifier is the
training structure's (1 = no benefit). Civs override it on their own versions of
a structure (e.g. structures/athen/dock 0.7 against the generic dock's 0.8).

One value per civ and RTS0 BuildingType: a generic type reads
structures/<civ>/<stem>.xml when the civ has one, else the generic template; a
civ-specific type reads its own template (tools/extract_0ad_attack.py). A
structure with no Trainer gets 1.

It also writes each civ's own trainer lists: the "units/{civ}/<name>" entries of
its structure of each type. Trainer.js fills {civ} with the owner's civ, so a
structure captured by another civ trains the captor's units of those names.

Usage:
  python3 -I tools/extract_0ad_trainer.py --0ad PATH/TO/0ad [--check]

Writes src/simulation/trainer_data.h. --check fails if the checked-in file differs.
"""

import argparse
import importlib.util
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_HEADER = os.path.join(REPO, "src", "simulation", "trainer_data.h")

_spec = importlib.util.spec_from_file_location("extract_0ad_attack",
                                               os.path.join(REPO, "tools", "extract_0ad_attack.py"))
atk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(atk)
ex = atk.ex

# Each civ's own version of a generic structure: structures/<civ>/<stem>.xml.
CIV_STEM = {
    "BLD_TOWN_CENTER": "civil_centre", "BLD_HOUSE": "house", "BLD_BARRACKS": "barracks",
    "BLD_MARKET": "market", "BLD_FORTRESS": "fortress", "BLD_TEMPLE": "temple",
    "BLD_WONDER": "wonder", "BLD_DOCK": "dock", "BLD_CORRAL": "corral", "BLD_STABLE": "stable",
    "BLD_RANGE": "range", "BLD_ARSENAL": "arsenal", "BLD_ELEPHANT_STABLE": "elephant_stable",
    "BLD_THEATER": "theater", "BLD_EMBASSY": "embassy",
}


def modifier(t):
    if t.get("Trainer") is None:
        return 1.0
    return t.num("Trainer/BatchTimeModifier", 1.0)


def civ_list(t):
    """The <name>s of a structure's "units/{civ}/<name>" Trainer entries, in order."""
    if t.get("Trainer") is None:
        return []
    return [e[len("units/{civ}/"):] for e in t.tokens("Trainer/Entities") if e.startswith("units/{civ}/")]


def emit(types, table, lists):
    f = atk.f
    out = []
    w = out.append
    w("// Generated by tools/extract_0ad_trainer.py from 0 A.D.'s simulation templates; do not edit.")
    w("// 0 A.D. data is CC BY-SA 3.0 / GPL-2.0-or-later (see docs/0AD_ATTRIBUTION.md).")
    w("// Included by sim_types.h inside namespace rtso.")
    w("#pragma once")
    w("")
    w("// Trainer/BatchTimeModifier by civ (Civilization order) and BuildingType: a batch of n")
    w("// units trains in BuildTime * n^modifier (Trainer.js GetBatchTime); 1 = no batch benefit.")
    w("inline constexpr uint8_t TRAINER_BUILDING_ROWS = %d;" % len(types))
    w("inline constexpr uint8_t TRAINER_CIV_ROWS = %d;" % len(table))
    w("inline float trainer_batch_time_modifier(uint8_t civ, uint8_t type) {")
    w("\tstatic const float kTable[TRAINER_CIV_ROWS][TRAINER_BUILDING_ROWS] = {")
    for civ, row in table:
        w("\t\t{%s}, // %s" % (", ".join(f(v) for v in row), civ))
    w("\t};")
    w("\tif (civ >= TRAINER_CIV_ROWS || type >= TRAINER_BUILDING_ROWS) return 1.0f;")
    w("\treturn kTable[civ][type];")
    w("}")
    w("")
    w("// Trainer/Entities \"units/{civ}/<name>\" of each civ's own structure of a type (its")
    w("// structures/<civ>/ template): Trainer.js fills {civ} with the holder's civ, so a structure")
    w("// captured by another civ trains the captor's units of these names. Space-separated.")
    w("struct TrainerCivList {")
    w("\tuint8_t civ;")
    w("\tuint8_t type;")
    w("\tconst char *units;")
    w("};")
    w("inline constexpr TrainerCivList TRAINER_CIV_LISTS[] = {")
    for ci, civ, _ti, bld, names in lists:
        w("\t{%d, %s, \"%s\"}, // %s" % (ci, bld, " ".join(names), civ))
    w("};")
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--0ad", dest="zad", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sim_root = os.path.join(args.zad, "binaries", "data", "mods", "public", "simulation")
    loader = ex.TemplateLoader(sim_root)
    types = atk.BUILDINGS + atk.civ_buildings()
    table = []
    for civ in ex.CIV_SLOTS:
        if civ is None:  # CIV_GAIA trains nothing
            table.append(("gaia", [1.0] * len(types)))
            continue
        row = []
        for bld, name in types:
            stem = CIV_STEM.get(bld)
            own = "structures/%s/%s" % (civ, stem) if stem else None
            row.append(modifier(loader.load(own if own and loader.exists(own) else name)))
        table.append((civ, row))
    # A civ's own version of a generic structure, or a civ-specific one in structures/<civ>/.
    lists = []
    for ci, civ in enumerate(ex.CIV_SLOTS):
        if civ is None:
            continue
        for ti, (bld, name) in enumerate(types):
            stem = CIV_STEM.get(bld)
            own = "structures/%s/%s" % (civ, stem) if stem else name
            if not own.startswith("structures/%s/" % civ) or not loader.exists(own):
                continue
            names = civ_list(loader.load(own))
            if names:
                lists.append((ci, civ, ti, bld, names))
    text = emit(types, table, lists)
    if args.check:
        old = open(OUT_HEADER).read() if os.path.exists(OUT_HEADER) else ""
        if old != text:
            sys.exit("trainer_data.h is out of date")
        print("trainer_data.h is up to date")
        return
    with open(OUT_HEADER, "w") as fh:
        fh.write(text)
    print("wrote %s (%d civs x %d building types)" % (OUT_HEADER, len(table), len(types)))


if __name__ == "__main__":
    main()
